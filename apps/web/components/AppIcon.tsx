/** A coloured badge with an account's or category's icon. Decorative: the name carries the meaning. */
export function AppIcon({ icon, colour, size = "md" }: { icon: string; colour: string; size?: "sm" | "md" }) {
  const Icon = ICONS[icon as AppearanceIcon] ?? Package;
  const hex = (ACCOUNT_COLOURS[colour as AccountColour] ?? ACCOUNT_COLOURS.slate).light;
  return (
    <span
      aria-hidden="true"
      className={`inline-flex shrink-0 items-center justify-center rounded-full text-white ${size === "sm" ? "size-7" : "size-9"}`}
      style={{ backgroundColor: hex }}
    >
      <Icon className={size === "sm" ? "size-4" : "size-5"} />
    </span>
  );
}
